// Generates src/styles/tokens.css from design/tokens.json (Alter Pedro tokens v2.1.0).
// Source of truth = design/tokens.json. Do not hand-edit tokens.css.
// Light mode is the default (:root). Dark values are emitted under [data-theme="dark"] only (not auto-applied).
// Only the token groups this site uses are emitted (colour, type, spacing, radius, border, shadow, motion, containers, control height).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));
const out = join(root, 'src/styles/tokens.css');

const light = [], dark = [];
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const isMode = (o) => o && typeof o === 'object' && 'light' in o && 'dark' in o;

function walkColor(obj, path) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('_')) continue;
    if (isMode(v)) {
      const name = `--color-${[...path, k].map(kebab).join('-')}`;
      light.push(`${name}: ${v.light};`);
      if (v.dark !== v.light) dark.push(`${name}: ${v.dark};`);
    } else if (v && typeof v === 'object') walkColor(v, [...path, k]);
  }
}
const { focusRing, ...colorRest } = t.color;
walkColor(colorRest, []);

const plain = [];
const add = (name, val) => plain.push(`${name}: ${val};`);
add('--focus-ring-color', 'var(--color-accent-fill)');
add('--focus-ring-width', focusRing.width);
add('--focus-ring-offset', focusRing.offset);
for (const k of ['sans', 'mono', 'display']) add(`--font-${k}`, t.typography.fontFamily[k]);
for (const [k, v] of Object.entries(t.typography.scale)) {
  add(`--type-${k}-size`, v.size); add(`--type-${k}-weight`, v.weight);
  add(`--type-${k}-line`, v.lineHeight); add(`--type-${k}-tracking`, v.tracking);
}
add('--numeric-features', t.typography.numeric.featureSettings);
for (const [k, v] of Object.entries(t.spacing.scale)) add(`--space-${k}`, v);
for (const [k, v] of Object.entries(t.radius)) add(`--radius-${k}`, v);
for (const [k, v] of Object.entries(t.border.width)) add(`--border-${k}`, v);
add('--shadow-sm', t.shadow.sm); add('--shadow-md', t.shadow.md);
for (const k of ['fast', 'base', 'slow']) add(`--duration-${k}`, t.motion.duration[k]);
add('--ease-out', t.motion.easing.out);
for (const [k, v] of Object.entries(t.container)) if (!k.startsWith('_')) add(`--container-${k}`, v);
add('--control-height', t.density.comfortable.controlHeight);
add('--opacity-disabled', t.opacity.disabled);

// Semantic aliases used by the page. Errors use AMBER (warning), never red (danger is reserved for destructive actions and is not used on this site).
const alias = [
  '--color-ink: var(--color-neutral-900);',
  '--color-ink-hover: var(--color-neutral-800);',
  '--color-ink-active: var(--color-neutral-700);',
  '--color-error-text: var(--color-semantic-warning-text);',
  '--color-error-bg: var(--color-semantic-warning-subtle);',
  '--color-error-border: var(--color-semantic-warning-fill);',
];

const block = (sel, lines) => `${sel} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;
const css =
`/* GENERATED by scripts/gen-tokens.mjs from design/tokens.json (Alter Pedro tokens v${t.meta.version}). DO NOT EDIT BY HAND. */
/* Light mode is default. Wine accent = --color-accent-*; use on at most 3 elements per screen (enforced by scripts/check-build.mjs). */
${block(':root', [...light, ...plain, ...alias])}
${block('[data-theme="dark"]', dark)}`;

if (!existsSync(out) || readFileSync(out, 'utf8') !== css) writeFileSync(out, css);
console.log(`tokens: ${light.length} light colours, ${dark.length} dark overrides, ${plain.length} other tokens -> src/styles/tokens.css`);
