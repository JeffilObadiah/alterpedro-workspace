// Writes src/site-config.json from the build environment so the Worker and the page agree on one switch.
// sprintEnabled = SPRINT_PRICE is set and non-empty. The price itself is NOT stored (the Worker never needs it).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const out = new URL('../src/site-config.json', import.meta.url);
const sprintEnabled = (process.env.SPRINT_PRICE ?? '').trim() !== '';
const text = JSON.stringify({ _note: 'GENERATED by scripts/gen-site-config.mjs at build time from SPRINT_PRICE. Do not edit.', sprintEnabled }, null, 2) + '\n';
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text);
console.log(`site-config: sprintEnabled=${sprintEnabled} (${sprintEnabled ? 'two doors' : 'single door'})`);
